import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

/**
 * MindGym forest backdrop pipeline.
 *
 * The source art is eight camera-original JPEGs — up to 8229x5486 and 7.5 MB
 * each, 40.7 MB for the set. ForestBackdrop picks one at random and paints it
 * as a full-bleed `position: fixed` layer under three wash/vignette overlays,
 * on `/mindgym`, `/mindgym/section/:id` and the hub.
 *
 * Two costs, both paid on a phone on Indian mobile data:
 *   - the download, up to 7.5 MB for one decorative backdrop
 *   - the decode. 8229x5486 is ~180 MB of bitmap once expanded, which is a
 *     multi-second stall and a plausible OOM on a low-end Android.
 *
 * Nothing about the design needs that resolution: the image is washed with
 * `#f3ead9`/35 under `mix-blend-multiply`, a sunbeam gradient and a vignette,
 * and the `faded` variant masks off everything below ~82%.
 *
 *   node scripts/optimize-forest-backdrops.mjs [source-dir]
 *
 * Writes AVIF + WebP + a JPEG fallback into src/assets/mindgym/forest/ and a
 * manifest the component imports. Outputs are content-hashed: Vite serves
 * hashed assets with immutable cache headers, so a changed image MUST get a
 * changed filename — rename-on-change is the whole contract.
 */

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(repoRoot, "src", "assets", "mindgym", "forest");
const defaultSource = path.join(repoRoot, "art-source", "mindgym-forest");

/**
 * Two rungs. 1600 covers a desktop viewport; 960 covers every phone this app
 * actually runs on (a 412pt viewport at DPR 2 asks for 824). There is no 2400
 * rung because nothing here is meant to be looked at closely — see above.
 */
const WIDTHS = [960, 1600];
const QUALITY = { avif: 46, webp: 68, jpeg: 72 };

const widestFor = (meta) => Math.min(WIDTHS[WIDTHS.length - 1], meta.width);

const formatMb = (bytes) => `${(bytes / 1024 / 1024).toFixed(2)} MB`;
const formatKb = (bytes) => `${(bytes / 1024).toFixed(0)} KB`;

const sourceDir = process.argv[2] ?? defaultSource;
if (!existsSync(sourceDir)) {
  console.error(`Source directory not found: ${sourceDir}`);
  process.exit(1);
}

const sources = readdirSync(sourceDir)
  .filter((f) => /^\d+\.jpe?g$/i.test(f))
  .sort((a, b) => parseInt(a, 10) - parseInt(b, 10));

if (sources.length === 0) {
  console.error(`No numbered JPEGs in ${sourceDir}`);
  process.exit(1);
}

mkdirSync(outDir, { recursive: true });

const manifest = {};
let totalIn = 0;
let totalOut = 0;
/** The variant a phone actually downloads, tracked so the summary can't drift. */
let phoneBytes = 0;

for (const file of sources) {
  const sourcePath = path.join(sourceDir, file);
  const base = path.basename(file, path.extname(file));
  const inBytes = statSync(sourcePath).size;
  totalIn += inBytes;

  const meta = await sharp(sourcePath).metadata();
  const entry = { avif: {}, webp: {}, jpeg: {} };

  for (const width of WIDTHS) {
    const target = Math.min(width, meta.width);
    // AVIF and WebP get every rung; the JPEG exists only so `<img src>` has
    // something to point at on a browser that took neither <source>, and one
    // rung covers that. Emitting a 960 JPEG nothing references just leaves a
    // file in git that Rollup then tree-shakes back out of the build.
    const formats = target === widestFor(meta) ? ["avif", "webp", "jpeg"] : ["avif", "webp"];
    for (const format of formats) {
      const buffer = await sharp(sourcePath)
        .resize({ width: target, withoutEnlargement: true })
        .toFormat(format, { quality: QUALITY[format] })
        .toBuffer();

      const hash = createHash("sha256").update(buffer).digest("hex").slice(0, 8);
      const name = `${base}-${target}.${hash}.${format === "jpeg" ? "jpg" : format}`;
      writeFileSync(path.join(outDir, name), buffer);
      entry[format][target] = name;
      totalOut += buffer.length;
      if (format === "avif" && target === Math.min(960, meta.width)) phoneBytes += buffer.length;
    }
  }

  const widest = widestFor(meta);
  entry.width = widest;
  entry.height = Math.round((meta.height / meta.width) * widest);
  manifest[base] = entry;

  console.log(
    `${file.padEnd(8)} ${String(meta.width) + "x" + meta.height}`.padEnd(24) +
      `${formatMb(inBytes).padStart(9)} → ${WIDTHS.join("/")}px avif+webp+jpg`,
  );
}

// TypeScript rather than JSON: tsconfig.app.json does not set
// `resolveJsonModule`, and this gives the component a real union of the names.
const names = Object.keys(manifest);
const lines = [
  "// Generated by scripts/optimize-forest-backdrops.mjs — do not edit by hand.",
  "// Re-run the script after changing the source art in art-source/mindgym-forest/.",
  "",
  ...names.flatMap((name) =>
    ["avif", "webp", "jpeg"].flatMap((fmt) =>
      Object.entries(manifest[name][fmt]).map(
        ([w, file]) =>
          `import f${name}_${fmt}_${w} from "./${file}";`,
      ),
    ),
  ),
  "",
  `export const FOREST_WIDTHS = [${WIDTHS.join(", ")}] as const;`,
  "",
  "export interface ForestBackdropSources {",
  "  avif: string;",
  "  webp: string;",
  "  fallback: string;",
  "  width: number;",
  "  height: number;",
  "}",
  "",
  "/** srcSet strings, keyed by the backdrop's number as it appears on disk. */",
  "export const forestBackdrops: Record<string, ForestBackdropSources> = {",
  ...names.map((name) => {
    const srcset = (fmt) =>
      Object.entries(manifest[name][fmt])
        .map(([w]) => `\${f${name}_${fmt}_${w}} ${w}w`)
        .join(", ");
    const widest = Math.max(...Object.keys(manifest[name].jpeg).map(Number));
    return (
      `  "${name}": { avif: \`${srcset("avif")}\`, webp: \`${srcset("webp")}\`, ` +
      `fallback: f${name}_jpeg_${widest}, width: ${manifest[name].width}, height: ${manifest[name].height} },`
    );
  }),
  "};",
  "",
  "export const FOREST_BACKDROP_NAMES = Object.keys(forestBackdrops);",
  "",
];

writeFileSync(path.join(outDir, "manifest.ts"), lines.join("\n"), "utf8");

console.log(
  `\n${sources.length} backdrops: ${formatMb(totalIn)} → ${formatMb(totalOut)} ` +
    `across ${WIDTHS.length} widths.
` +
    `A phone loads one 960px AVIF: ${formatKb(phoneBytes / sources.length)} on average, ` +
    `down from ${formatMb(totalIn / sources.length)}.`,
);
