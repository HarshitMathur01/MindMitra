import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";

/**
 * Shared bits of the Night River image pipeline.
 *
 * `optimize-river-images.mjs` is the real generator and owns the whole
 * manifest. `backfill-river-lqip.mjs` only fills in the `lqip` field. Both
 * write src/assets/river/manifest.ts, so the serialiser lives here — two
 * copies of this banner would drift the moment either script changed.
 */

/**
 * Placeholder width. 20px is the point where the blur reads as *this* painting
 * rather than a generic smudge, and still encodes to ~130 bytes — under 200
 * bytes as base64, comfortably below Vite's 4 KB `assetsInlineLimit`, so it
 * costs no request at all.
 */
export const LQIP_WIDTH = 20;
const LQIP_QUALITY = 45;

/** A ~20px WebP of `input` (path or Buffer) as a base64 data URI. */
export async function makeLqip(input) {
  const buffer = await sharp(input)
    .resize({ width: LQIP_WIDTH })
    .webp({ quality: LQIP_QUALITY, effort: 6 })
    .toBuffer();
  return `data:image/webp;base64,${buffer.toString("base64")}`;
}

const BANNER = `// GENERATED by scripts/optimize-river-images.mjs — do not edit by hand.
// Re-run the script against the source art to regenerate.
//
// Filenames are content-hashed; Vite serves them immutable, so a changed image
// only reaches users under a new name.
//
// \`lqip\` is a ~${LQIP_WIDTH}px WebP inlined as a data URI. RiverImage paints it as a
// background under the real image, so a loading tile shows the painting's
// colours instead of an empty box. It is ~200 bytes; do not grow it into a
// second image budget.

export interface RiverImageEntry {
  /** width (px) → filename */
  readonly avif: Readonly<Record<number, string>>;
  readonly webp: Readonly<Record<number, string>>;
  /** intrinsic size of the largest variant, for aspect-ratio reservation */
  readonly width: number;
  readonly height: number;
  /** ~${LQIP_WIDTH}px WebP data URI painted while the real image loads */
  readonly lqip: string;
}
`;

/**
 * Reads src/assets/river/manifest.ts back into a plain object.
 *
 * The file is TypeScript, so it cannot just be imported here. It is also
 * generated by `writeManifest` below, which means the bit between the first
 * `{` and the trailing `as const` is always `JSON.stringify` output — parsing
 * it is exact, not a guess. Returns `{}` when the manifest does not exist yet.
 *
 * Only `--merge` runs need this; a default run overwrites the manifest whole.
 */
export function readManifest(outDir) {
  const file = path.join(outDir, "manifest.ts");
  if (!existsSync(file)) return {};
  const source = readFileSync(file, "utf8");
  const start = source.indexOf("export const RIVER_MANIFEST = ");
  if (start === -1) return {};
  const open = source.indexOf("{", start);
  const close = source.lastIndexOf("} as const");
  if (open === -1 || close === -1) return {};
  return JSON.parse(source.slice(open, close + 1));
}

/** Writes src/assets/river/manifest.ts from a plain manifest object. */
export function writeManifest(manifest, outDir) {
  const source = `${BANNER}
export const RIVER_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, RiverImageEntry>;

export type RiverImageName = keyof typeof RIVER_MANIFEST;
`;
  writeFileSync(path.join(outDir, "manifest.ts"), source);
}
